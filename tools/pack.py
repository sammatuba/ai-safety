#!/usr/bin/env python3
"""Bundle the routed files for a task into one Markdown document.

Purpose: tools that cannot read the filesystem (ChatGPT web, DeepSeek web UI) still get
the same context an agent in the repository would load. The routing table is
``tools/routes.json``; ``INDEX.md`` mirrors it for humans.

Usage:
    python3 tools/pack.py sprint              # print bundle to stdout
    python3 tools/pack.py sprint -o out.md    # write bundle to a file
    python3 tools/pack.py --list              # list tasks
    python3 tools/pack.py --check             # verify every routed file exists

The bundle starts with a short header that tells the receiving model what it is reading
and which rules apply, then each file under a level-1 heading with its path.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROUTES = ROOT / "tools" / "routes.json"

HEADER = """\
# Context bundle: task `{task}`

Generated by `tools/pack.py` from the ai-safety research repository on {root}.
This bundle contains {n} files. Treat them as working context, not as proof of novelty
or completed results. Follow the rules in AGENTS.md (section 3) and use GLOSSARY.md
terms verbatim. Statement kinds are tagged where they could be confused:
[ESTABLISHED] [FINDING] [INTERPRETATION] [HYPOTHESIS] [SPECULATION].

Files in this bundle:
{listing}

---
"""


def load_routes() -> dict[str, list[str]]:
    data = json.loads(ROUTES.read_text(encoding="utf-8"))
    return {k: v for k, v in data.items() if not k.startswith("_")}


def check(routes: dict[str, list[str]]) -> int:
    missing = 0
    for task, files in routes.items():
        for rel in files:
            if not (ROOT / rel).exists():
                print(f"MISSING  {task:16s} {rel}")
                missing += 1
    print(f"{missing} missing file(s) across {len(routes)} tasks")
    return 1 if missing else 0


def bundle(task: str, routes: dict[str, list[str]]) -> str:
    files = routes[task]
    parts = [
        HEADER.format(
            task=task,
            root=ROOT.name,
            n=len(files),
            listing="\n".join(f"- `{f}`" for f in files),
        )
    ]
    for rel in files:
        path = ROOT / rel
        if not path.exists():
            parts.append(f"\n# FILE: {rel}\n\n(missing on disk)\n")
            continue
        parts.append(f"\n# FILE: {rel}\n\n{path.read_text(encoding='utf-8')}\n")
    return "".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("task", nargs="?", help="task name from routes.json")
    ap.add_argument("-o", "--out", help="write bundle to this path")
    ap.add_argument("--list", action="store_true", help="list task names")
    ap.add_argument("--check", action="store_true", help="verify routed files exist")
    args = ap.parse_args()
    routes = load_routes()
    if args.list:
        for k, v in routes.items():
            print(f"{k:16s} {len(v):2d} files")
        return 0
    if args.check:
        return check(routes)
    if not args.task or args.task not in routes:
        print(f"unknown task {args.task!r}; use --list", file=sys.stderr)
        return 2
    text = bundle(args.task, routes)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out} ({len(text):,} chars)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
