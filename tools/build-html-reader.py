#!/usr/bin/env python3
"""Build an offline HTML reader from Git-visible Markdown documents.

Markdown stays canonical. Ignored files are excluded, including raw downloads and secrets.
Run from the repository root with: cd lab && uv run python ../tools/build-html-reader.py
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

from markdown_it import MarkdownIt

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "explainer/assets/reader-data.js"


def github_slug(text: str) -> str:
    """Create a GitHub-style heading fragment from visible heading text."""
    text = re.sub(r"[^\w\- ]", "", text.lower(), flags=re.UNICODE)
    return text.replace(" ", "-")


def render_document(source: str) -> dict[str, str]:
    """Render a document and assign stable heading fragments, including duplicates."""
    source = re.sub(r"\A---\s*\n.*?\n---\s*\n", "", source, count=1, flags=re.S)
    parser = MarkdownIt("commonmark", {"html": False}).enable(["table", "strikethrough"])
    tokens = parser.parse(source)
    counts: dict[str, int] = {}
    title = ""
    for index, token in enumerate(tokens):
        if token.type != "heading_open":
            continue
        inline = tokens[index + 1]
        visible = "".join(t.content for t in inline.children or [] if t.type in {"text", "code_inline", "image"})
        if not title and token.tag == "h1":
            title = visible
        slug = github_slug(visible)
        occurrence = counts.get(slug, 0)
        counts[slug] = occurrence + 1
        token.attrSet("id", slug if occurrence == 0 else f"{slug}-{occurrence}")
    return {"title": title, "html": parser.renderer.render(tokens, parser.options, {})}


def main() -> None:
    names = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"], cwd=ROOT
    ).decode("utf-8").split("\0")
    paths = sorted({name for name in names if name.lower().endswith(".md") and (ROOT / name).is_file()})
    documents = {name: render_document((ROOT / name).read_text(encoding="utf-8")) for name in paths}
    payload = json.dumps(documents, ensure_ascii=False, separators=(",", ":"))
    OUTPUT.write_text("/* Generated by tools/build-html-reader.py. Do not edit. */\nwindow.READER_DOCUMENTS=" + payload + ";\n", encoding="utf-8")
    print(f"Built {len(documents)} Markdown documents into {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
