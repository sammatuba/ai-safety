#!/usr/bin/env python3
"""Build the explainer's glossary data from GLOSSARY.md.

The Markdown glossary stays canonical. This script extracts each term, its
definition, and its banned synonyms into a JavaScript data file that the
static explainer can load without a server or a build step.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "GLOSSARY.md"
TARGET = ROOT / "explainer" / "assets" / "glossary-data.js"

SECTION_RE = re.compile(r"^## (\d+)\. (.+)$")
TERM_RE = re.compile(r"^\|\s*\*\*(.+?)\*\*\s*\|")


def clean(cell: str) -> str:
    cell = cell.strip().replace("\\|", "|").replace("**", "")
    return re.sub(r"\s+", " ", cell)


def parse() -> list[dict[str, str]]:
    terms: list[dict[str, str]] = []
    section = ""
    for raw in SOURCE.read_text(encoding="utf-8").splitlines():
        section_match = SECTION_RE.match(raw.strip())
        if section_match:
            section = section_match.group(2).strip()
            continue
        if not raw.startswith("|") or not TERM_RE.match(raw):
            continue
        cells = re.split(r"(?<!\\)\|", raw.strip())
        if len(cells) < 4:
            continue
        term = clean(cells[1])
        definition = clean(cells[2])
        banned = clean(cells[3])
        terms.append(
            {
                "section": section,
                "term": term,
                "definition": definition,
                "banned": "" if banned in {"", "—"} else banned,
            }
        )
    return terms


def main() -> None:
    terms = parse()
    sections: list[str] = []
    for item in terms:
        if item["section"] not in sections:
            sections.append(item["section"])
    payload = {
        "sections": sections,
        "terms": terms,
    }
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(payload, ensure_ascii=False, indent=2)
    TARGET.write_text(
        "/* Generated by tools/build-glossary.py from GLOSSARY.md. Do not edit by hand. */\n"
        f"window.GLOSSARY_DATA = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(terms)} terms in {len(sections)} sections to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
